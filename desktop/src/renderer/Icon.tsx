// An icon in front of a label. Inside a filled button (Save, Send, the confirming Delete) it
// takes the button's text color instead of its own.
export function Icon({ name, tone, spin }: { name: IconName; tone?: Tone; spin?: boolean }) {
  const className = `icon tone-${tone ?? TONES[name] ?? "muted"}${spin ? " spin" : ""}`;
  return (
    <i className={className} aria-hidden="true">
      {String.fromCodePoint(GLYPHS[name])}
    </i>
  );
}
